using UnityEngine;

public class singleton : MonoBehaviour
{
    public static singleton Instance { get; set; }
    
    void Awake() 
    { 
        // If there is an instance, and it's not me, delete myself.
    
        if (Instance != null && Instance != this) 
        { 
            Destroy(this); 
        } 
        else 
        { 
            Instance = this; 
        } 
    }
}
